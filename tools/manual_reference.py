#!/usr/bin/env python3
"""Builds docs/manual/reference.md (the plain-English knob reference) from docs/parameters.json.

    EmberlineTools dump-params docs        # refresh docs/parameters.json first
    python3 tools/manual_reference.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
data = json.load(open(os.path.join(ROOT, "docs", "parameters.json")))
params = data["parameters"] if isinstance(data, dict) else data

# plain-English notes per parameter id (anything not listed just shows its range and default)
NOTE = {
    "master_volume": "Overall level.",
    "sub_level": "Sub oscillator level.", "sub_wave": "Sub waveform.", "sub_oct": "How far below the note the sub plays.",
    "noise_level": "Noise level.", "noise_type": "White is bright, pink is softer, crackle is vinyl-like.",
    "filt_routing": "Serial: filter 1 then filter 2. Parallel: both at once, then mixed.",
    "analog_drift": "Slow pitch wander and per-note tuning differences. 0 = perfectly stable.",
    "analog_warmth": "Soft saturation plus a gentle treble roll-off. 0 = clean.",
    "global_tempo": "Tempo used when there is no DAW (Standalone).", "pitch_bend_range": "Pitch wheel range in semitones.",
    "chaos_rate": "Speed of the Lorenz chaos engine.", "fractal_rate": "Speed of Perlin and S&H.",
}
SUFFIX = {
    "on": "On/off.", "level": "Level.", "table": "Wavetable.", "frame": "Position in the wavetable.", "warp_mode": "Warp type.",
    "warp_amt": "Warp amount.", "unison": "Number of stacked voices.", "detune": "Detune between the unison voices (cents).",
    "spread": "Stereo spread of the unison voices.", "semi": "Tuning in semitones.", "fine": "Fine tuning in cents.", "pan": "Left/right position.",
    "type": "Filter type.", "slope": "Filter steepness.", "cutoff": "Cutoff frequency.", "res": "Resonance.", "drive": "Drive into the filter.",
    "rate": "Speed.", "mode": "Retrig restarts on each note; Free runs on.", "sync": "Tempo sync note length (Off = use the rate).",
    "attack": "Attack time.", "decay": "Decay time.", "sustain": "Sustain level.", "release": "Release time.", "acurve": "Attack curve.", "dcurve": "Decay curve.",
}
SECTIONS = [
    ("Oscillators", r"^osc[123]_"), ("Sub and noise", r"^(sub|noise)_"), ("Filters", r"^filt"), ("Master and analogue", r"^(master|analog|global|pitch)"),
    ("LFOs", r"^lfo"), ("Envelopes", r"^env"), ("Macros", r"^macro"), ("Chaos", r"^(chaos|fractal)"),
    ("Effects", r"^fx_"), ("Arpeggiator and stutter", r"^arp_"),
]

def pretty(pid):
    m = re.match(r"^(osc|filt|lfo|env)(\d)_(.*)$", pid)
    if m:
        kind, n, rest = m.groups()
        name = {"osc": "OSC", "filt": "Filter", "lfo": "LFO", "env": "ENV"}[kind] + " " + n
        return name + " " + rest.replace("_", " ")
    return pid.replace("_", " ")

def rng(p):
    t = p.get("type")
    if t in ("choice",):
        ch = p.get("choices") or p.get("range") or []
        text = " / ".join(ch) if isinstance(ch, list) else str(ch)
        return text if len(text) < 90 else f"{len(ch)} choices"
    if t == "bool": return "on / off"
    lo, hi = p.get("min"), p.get("max")
    fmt = lambda v: ("%g" % round(v, 3)) if isinstance(v, (int, float)) else str(v)
    return f"{fmt(lo)} to {fmt(hi)}" + (f" {p['unit']}" if p.get("unit") else "")

def note(pid):
    if pid in NOTE: return NOTE[pid]
    suffix = re.sub(r"^(osc|filt|lfo|env)\d_", "", pid)
    return SUFFIX.get(suffix, "")

lines = ["# Knob reference", "",
         "Every control in the synth, with its range and where it starts. _Generated by `tools/manual_reference.py`, so don't edit by hand._", "",
         "Controls on the three oscillators, filters, LFOs and envelopes repeat for each number, so only the first is listed in full.", "",
         "The modulation matrix has 16 rows (source, destination, depth, curve, bipolar); those are covered in [Moving things around](04-modulation.md).", ""]
for title, pat in SECTIONS:
    rows = []
    for p in params:
        pid = p["id"]
        if not re.search(pat, pid) or re.match(r"^(osc|filt|lfo|env)[2-9]_", pid): continue   # repeats of the first one
        d = p.get("default")
        rows.append((pretty(pid), rng(p), ("on" if d else "off") if p.get("type") == "bool" else d, note(pid)))
    if rows:
        lines += [f"## {title}", "", "| control | range | default | what it does |", "|---|---|---|---|"]
        for name, r, d, n in rows:
            lines.append(f"| {name} | {r} | {d} | {n} |")
        lines.append("")
lines += ["## Moving things (modulation sources)", "", ", ".join(s["name"] for s in data["modulation_sources"]) if isinstance(data, dict) else "", "",
          "## Things you can modulate", "", ", ".join(d["label"] for d in data["modulation_destinations"]) if isinstance(data, dict) else "", ""]
open(os.path.join(ROOT, "docs", "manual", "reference.md"), "w").write("\n".join(lines))
print("wrote docs/manual/reference.md")
