    // ------------------------------------------------------------------ parameter catalogue
    juce::var describe (juce::RangedAudioParameter& p)
    {
        auto* o = new juce::DynamicObject();
        o->setProperty ("id", p.getParameterID());
        o->setProperty ("name", p.getName (64));

        const auto range = p.getNormalisableRange();
        const auto def = p.convertFrom0to1 (p.getDefaultValue());

        if (auto* c = dynamic_cast<juce::AudioParameterChoice*> (&p))
        {
            o->setProperty ("type", "choice");
            juce::Array<juce::var> choices;
            for (auto& s : c->choices) choices.add (s);
            o->setProperty ("choices", choices);
            o->setProperty ("default", c->choices[juce::roundToInt (def)]);
        }
        else if (dynamic_cast<juce::AudioParameterBool*> (&p) != nullptr)
        {
            o->setProperty ("type", "bool");
            o->setProperty ("default", def > 0.5f);
        }
        else
        {
            o->setProperty ("type", dynamic_cast<juce::AudioParameterInt*> (&p) != nullptr ? "int" : "float");
            o->setProperty ("min", range.start);
            o->setProperty ("max", range.end);
            o->setProperty ("default", std::round ((double) def * 10000.0) / 10000.0);
            if (p.getLabel().isNotEmpty()) o->setProperty ("unit", p.getLabel());
            if (std::abs (range.skew - 1.0f) > 1.0e-3f) o->setProperty ("skew", range.skew);
        }
        return juce::var (o);
    }

    int dumpParams (EmberlineProcessor& proc, const juce::File& dir)
    {
        dir.createDirectory();

        juce::Array<juce::var> params;
        juce::String md;
        md << "# Parameter catalogue\n\n_Generated by `EmberlineTools dump-params` - do not edit by hand._\n\n"
           << "| id | type | range / choices | default | unit |\n|---|---|---|---|---|\n";

        for (auto* prm : proc.getParameters())
        {
            auto* r = dynamic_cast<juce::RangedAudioParameter*> (prm);
            if (r == nullptr) continue;

            const auto v = describe (*r);
            params.add (v);

            juce::String detail;
            if (auto* choices = v.getProperty ("choices", {}).getArray())
            {
                juce::StringArray names;
                for (auto& c : *choices) names.add (c.toString());
                detail = names.joinIntoString (" / ");
            }
            else if (v.getProperty ("type", {}).toString() == "bool")
                detail = "true / false";
            else
                detail = v["min"].toString() + " .. " + v["max"].toString() + (v.hasProperty ("skew") ? " (skewed)" : "");

            md << "| `" << v["id"].toString() << "` | " << v["type"].toString() << " | " << detail << " | "
               << v["default"].toString() << " | " << v.getProperty ("unit", {}).toString() << " |\n";
        }

        auto* root = new juce::DynamicObject();
        root->setProperty ("parameters", params);

        juce::Array<juce::var> sources;
        const auto names = mod::sourceNames();
        md << "\n## Modulation sources (`source` in the `modulation` list)\n\n| name | native polarity |\n|---|---|\n";
        for (int s = 1; s < mod::numSources; ++s)
        {
            auto* o = new juce::DynamicObject();
            o->setProperty ("name", names[s]);
            o->setProperty ("bipolar", mod::isBipolar (s));
            sources.add (juce::var (o));
            md << "| " << names[s] << " | " << (mod::isBipolar (s) ? "bipolar (-1..1)" : "unipolar (0..1)") << " |\n";
        }
        root->setProperty ("modulation_sources", sources);

        juce::Array<juce::var> dests;
        md << "\n## Modulation destinations (`destination`: the label or the parameter id)\n\n| label | parameter id |\n|---|---|\n";
        for (auto& d : mod::destinations())
        {
            auto* o = new juce::DynamicObject();
            o->setProperty ("label", d.label);
            o->setProperty ("parameter", d.paramId);
            dests.add (juce::var (o));
            md << "| " << d.label << " | `" << d.paramId << "` |\n";
        }
        root->setProperty ("modulation_destinations", dests);

        // wavetable catalogue
        {
            auto& bank = WavetableBank::shared();
            juce::String wt;
            wt << "# Wavetable catalogue\n\n_Generated by `EmberlineTools dump-params` - do not edit by hand._\n\n"
               << "Select with the `oscN_table` parameter (by name). Frame (`oscN_frame`, 0..1) then moves through the table's 16 frames.\n\n"
               << "| index | name | category | what it does |\n|---|---|---|---|\n";
            for (int i = 0; i < bank.numFactoryTables(); ++i)
                wt << "| " << i << " | " << bank.info (i).name << " | " << bank.info (i).category << " | " << bank.info (i).description << " |\n";
            wt << "\nUser slots: `User 1` ... `User " << WavetableBank::numUserSlots << "` hold the first " << WavetableBank::numUserSlots
               << " `.json` / `.wav` files found in the user wavetable folder (see WAVETABLES.md).\n\n"
               << "## Functions available in wavetable expressions (name/number of arguments)\n\n";
            wt << Expression::functionNames().joinIntoString (", ") << "\n";
            dir.getChildFile ("wavetable-list.md").replaceWithText (wt, false, false, "\n");
        }

        dir.getChildFile ("parameters.json").replaceWithText (juce::JSON::toString (juce::var (root), false, 4), false, false, "\n");
        dir.getChildFile ("parameters.md").replaceWithText (md, false, false, "\n");
        std::printf ("wrote %s/parameters.json and parameters.md (%d parameters)\n", dir.getFullPathName().toRawUTF8(), params.size());
        return 0;
    }

    // ------------------------------------------------------------------ rendering
    struct Metrics
    {
        float peakDb = -120.0f, rmsDb = -120.0f, dcDb = -120.0f;
        float motion = 0.0f, width = 0.0f;   // % change of brightness over the held note, and 1 - L/R correlation, both in %
        bool finite = true;
        juce::AudioBuffer<float> audio;
    };

    std::vector<int> notesFor (const juce::String& category)
    {
        if (category == "Bass")                               return { 36 };
        if (category == "FX")                                 return { 48 };
        if (category == "Lead" || category == "Pluck" || category == "Arp") return { 60, 63, 67 };
        return { 48, 55, 58, 63 };
    }

    Metrics render (EmberlineProcessor& p, const juce::String& category)
    {
        p.prepareToPlay (sampleRate, blockSize);
        const auto notes = notesFor (category);
        // FX presets (risers, sweeps) need far longer to open up than a normal note
        const bool longForm = category == "FX";
        const int holdBlocks = (int) ((longForm ? 8.0 : 2.2) * sampleRate / blockSize),
                  totalBlocks = (int) ((longForm ? 12.0 : 6.0) * sampleRate / blockSize);

        Metrics m;
        m.audio.setSize (2, totalBlocks * blockSize);
        juce::AudioBuffer<float> block (2, blockSize);

        double sumL = 0.0;
        int counted = 0;
        float peak = 0.0f;
        std::vector<double> blockEnergy ((size_t) totalBlocks, 0.0);   // mean square per block, both channels

        for (int b = 0; b < totalBlocks; ++b)
        {
            juce::MidiBuffer midi;
            if (b == 0)
                for (int n : notes) midi.addEvent (juce::MidiMessage::noteOn (1, n, (juce::uint8) 100), 0);
            if (b == holdBlocks)
                for (int n : notes) midi.addEvent (juce::MidiMessage::noteOff (1, n), 0);

            p.processBlock (block, midi);

            for (int c = 0; c < 2; ++c)
            {
                const auto* x = block.getReadPointer (c);
                for (int i = 0; i < blockSize; ++i)
                {
                    if (! std::isfinite (x[i])) m.finite = false;
                    peak = std::max (peak, std::abs (x[i]));
                    blockEnergy[(size_t) b] += (double) x[i] * x[i] / (2.0 * blockSize);
                    if (b >= 8 && b < holdBlocks) { sumL += x[i]; ++counted; }
                }
                m.audio.copyFrom (c, b * blockSize, block, c, 0, blockSize);
            }
        }

        auto db = [] (double v) { return (float) (20.0 * std::log10 (std::max (v, 1.0e-6))); };
        m.peakDb = db (peak);
        // loudness = the loudest 300 ms window, so short plucks and long swells are judged fairly
        const int window = juce::jmax (1, (int) (0.3 * sampleRate / blockSize));
        double best = 0.0;
        for (int start = 0; start + window <= totalBlocks; ++start)
        {
            double sum = 0.0;
            for (int k = 0; k < window; ++k) sum += blockEnergy[(size_t) (start + k)];
            best = std::max (best, sum / window);
        }
        m.rmsDb = db (std::sqrt (best));

        // how much does the sound change while the note is held, and how wide is it?
        {
            const int startSample = (int) (0.35 * sampleRate), endSample = (int) ((longForm ? 7.0 : 2.0) * sampleRate);
            juce::dsp::FFT fft (11);
            std::vector<float> fftData (4096);
            std::vector<double> centroids;
            for (int pos = startSample; pos + 2048 < endSample; pos += 4096)
            {
                std::fill (fftData.begin(), fftData.end(), 0.0f);
                for (int i = 0; i < 2048; ++i)
                    fftData[(size_t) i] = 0.5f * (m.audio.getSample (0, pos + i) + m.audio.getSample (1, pos + i))
                                          * (0.5f - 0.5f * std::cos (juce::MathConstants<float>::twoPi * (float) i / 2048.0f));
                fft.performFrequencyOnlyForwardTransform (fftData.data());
                double num = 0.0, den = 0.0;
                for (int k = 1; k < 1024; ++k) { num += (double) k * fftData[(size_t) k]; den += fftData[(size_t) k]; }
                if (den > 1.0e-6) centroids.push_back (num / den);
            }
            if (centroids.size() >= 3)
            {
                double mean = 0.0, var = 0.0;
                for (auto c : centroids) mean += c;
                mean /= (double) centroids.size();
                for (auto c : centroids) var += (c - mean) * (c - mean);
                m.motion = (float) (100.0 * std::sqrt (var / (double) centroids.size()) / std::max (mean, 1.0));
            }

            double ll = 0.0, rr = 0.0, lr = 0.0;
            for (int i = startSample; i < endSample; ++i)
            {
                const double l = m.audio.getSample (0, i), r = m.audio.getSample (1, i);
                ll += l * l; rr += r * r; lr += l * r;
            }
            m.width = (float) (100.0 * (1.0 - lr / std::sqrt (ll * rr + 1.0e-12)));
        }
        m.dcDb = counted > 0 ? db (std::abs (sumL / counted)) : -120.0f;
        return m;
    }

    bool writeWav (const juce::AudioBuffer<float>& audio, const juce::File& file)
    {
        file.deleteFile();
        juce::WavAudioFormat wav;
        std::unique_ptr<juce::AudioFormatWriter> w (wav.createWriterFor (new juce::FileOutputStream (file), sampleRate, 2, 16, {}, 0));
        return w != nullptr && w->writeFromAudioSampleBuffer (audio, 0, audio.getNumSamples());
    }

    // read the master_volume the preset asks for (default -6 dB), text-level so formatting survives
    double currentVolume (const juce::String& text)
    {
        const auto r = juce::String ("\"master_volume\"");
        const int at = text.indexOf (r);
        if (at < 0) return -6.0;
        return text.substring (text.indexOfChar (at, ':') + 1).getDoubleValue();
    }

    juce::String withVolume (juce::String text, double volumeDb)
    {
        const auto value = juce::String (std::round (volumeDb * 10.0) / 10.0, 1);
        const int at = text.indexOf ("\"master_volume\"");
        if (at >= 0)
        {
            const int colon = text.indexOfChar (at, ':');
            int end = colon + 1;
            while (end < text.length() && text[end] != ',' && text[end] != '\n' && text[end] != '}') ++end;
            return text.substring (0, colon + 1) + " " + value + text.substring (end);
        }

        const int params = text.indexOf ("\"parameters\"");
        const int brace = params >= 0 ? text.indexOfChar (params, '{') : -1;
        if (brace < 0) return text;

        // no trailing comma if the parameter block was empty (keeps the file strict JSON)
        const auto rest = text.substring (brace + 1);
        const bool empty = rest.trimStart().startsWithChar ('}');
        return text.substring (0, brace + 1) + "\n        \"master_volume\": " + value + (empty ? "\n    " : ",") + rest;
    }

    int check (EmberlineProcessor& proc, const juce::File& dir, const juce::File& wavDir, bool fixLevels, double targetDb)
    {
        auto files = dir.findChildFiles (juce::File::findFiles, false, "*.json");
        files.sort();
        if (wavDir != juce::File()) wavDir.createDirectory();

        int problems = 0, warned = 0, loud = 0, quiet = 0;
        std::printf ("%-44s %7s %7s %6s %6s  %s\n", "preset", "peak", "rms", "move%", "wide%", "notes");

        for (auto& f : files)
        {
            auto text = f.loadFileAsString();
            juce::var v;
            juce::String error;
            if (! presets::parse (text, v, error))
            {
                std::printf ("%-44s PARSE ERROR: %s\n", f.getFileName().toRawUTF8(), error.toRawUTF8());
                ++problems;
                continue;
            }

            juce::StringArray notes;
            const auto name = v["name"].toString(), category = v["category"].toString();
            if (name.isEmpty())     notes.add ("missing name");
            if (category.isEmpty()) notes.add ("missing category");
            if (v.getProperty ("description", {}).toString().isEmpty()) notes.add ("no description");
            if (v.getProperty ("author", {}).toString().isEmpty()) notes.add ("no author");

            auto result = presets::apply (proc, v);
            for (auto& w : result.warnings) notes.add ("WARN " + w);

            auto m = render (proc, category);
            if (! m.finite) notes.add ("NON-FINITE OUTPUT");
            if (m.rmsDb < -50.0f) notes.add ("SILENT");

            if (fixLevels && m.finite && m.rmsDb > -50.0f)
            {
                const double current = currentVolume (text);

                // very spiky material (plucks, stabs) reads quiet on a 300 ms RMS window, so ease its target down
                const double crest = (double) m.peakDb - (double) m.rmsDb;
                const double effectiveTarget = targetDb - juce::jlimit (0.0, 6.0, (crest - 12.0) * 0.5);

                // reach the target loudness, but never above -1 dBFS peak
                const double gain = std::min (effectiveTarget - (double) m.rmsDb, -1.0 - (double) m.peakDb);
                const double newVolume = juce::jlimit (-40.0, 6.0, current + gain);
                if (std::abs (newVolume - current) > 0.05)
                {
                    f.replaceWithText (withVolume (text, newVolume), false, false, "\n");
                    text = f.loadFileAsString();
                    presets::parse (text, v, error);
                    presets::apply (proc, v);
                    m = render (proc, category);
                    notes.add ("volume " + juce::String (current, 1) + " -> " + juce::String (newVolume, 1));
                }
            }

            // plainness guards: sustained sounds should change over time, and pads / textures should be wide
            const bool sustained = category == "Pad" || category == "Texture" || category == "Keys" || category == "Lead" || category == "Chord"
                                   || category == "Organic" || category == "Arp";
            if (sustained && m.motion < 1.0f) notes.add ("static");
            if ((category == "Pad" || category == "Texture") && m.width < 8.0f) notes.add ("narrow");

            if (m.peakDb > -0.5f) notes.add ("CLIPS");
            if (m.rmsDb > targetDb + 4.0f) { ++loud; notes.add ("loud"); }
            if (m.rmsDb < targetDb - 6.0f && m.rmsDb >= -50.0f) { ++quiet; notes.add ("quiet"); }

            if (wavDir != juce::File())
                writeWav (m.audio, wavDir.getChildFile (f.getFileNameWithoutExtension() + ".wav"));

            const bool bad = notes.joinIntoString (" ").containsAnyOf ("ERROR") || ! m.finite || m.rmsDb < -50.0f;
            if (bad) ++problems;
            if (! result.warnings.isEmpty()) ++warned;

            std::printf ("%-44s %7.1f %7.1f %6.1f %6.1f  %s\n", f.getFileNameWithoutExtension().toRawUTF8(), m.peakDb, m.rmsDb, m.motion, m.width,
                         notes.joinIntoString ("; ").toRawUTF8());
        }

        std::printf ("\n%d presets, %d with warnings, %d problems, %d loud, %d quiet\n", files.size(), warned, problems, loud, quiet);
        return problems > 0 ? 1 : 0;
    }
