WavetableBank::FileResolver resolverFor (const juce::File& dir)
{
    return [dir] (const juce::String& name, juce::MemoryBlock& out)
    {
        return dir.getChildFile (name).loadFileAsData (out) || dir.getChildFile ("Audio").getChildFile (name).loadFileAsData (out);
    };
}

int checkWavetables (const juce::File& dir)
{
    auto files = dir.findChildFiles (juce::File::findFiles, false, "*.json");
    files.sort();
    std::printf ("%-24s %4s %-9s %-9s %s\n", "wavetable", "id", "mode", "category", "notes");

    juce::StringArray names;
    juce::Array<int> ids;
    int problems = 0;

    for (auto& f : files)
    {
        juce::var v;
        const auto parsed = juce::JSON::parse (f.loadFileAsString(), v);
        if (parsed.failed())
        {
            std::printf ("%-24s INVALID JSON: %s\n", f.getFileName().toRawUTF8(), parsed.getErrorMessage().toRawUTF8());
            ++problems;
            continue;
        }

        auto built = WavetableBank::buildFromJson (v, resolverFor (dir));
        if (! built.ok)
        {
            std::printf ("%-24s ERROR: %s\n", f.getFileName().toRawUTF8(), built.error.toRawUTF8());
            ++problems;
            continue;
        }

        juce::StringArray notes;
        const int id = (int) v.getProperty ("id", -1);
        if (names.contains (built.info.name, true)) { notes.add ("DUPLICATE NAME"); ++problems; }
        if (id >= 0 && ids.contains (id)) { notes.add ("DUPLICATE ID"); ++problems; }
        names.add (built.info.name);
        if (id >= 0) ids.add (id);
        if (built.info.description.isEmpty()) notes.add ("no description");
        if (built.info.category.isEmpty())    notes.add ("no category");

        // does Frame actually change the sound?
        const auto* first = built.data.data();
        const auto* last = built.data.data() + (size_t) (WavetableBank::numFrames - 1) * WavetableBank::tableSize;
        double diff = 0.0;
        for (int n = 0; n < WavetableBank::tableSize; ++n) diff += std::abs ((double) first[n] - last[n]);
        diff /= WavetableBank::tableSize;
        if (diff < 0.02) notes.add ("first and last frame are nearly identical");

        std::printf ("%-24s %4d %-9s %-9s frame 1 vs 16 differ by %.2f%s%s\n", built.info.name.toRawUTF8(), id,
                     v["mode"].toString().toRawUTF8(), built.info.category.toRawUTF8(), diff,
                     notes.isEmpty() ? "" : "  <- ", notes.joinIntoString ("; ").toRawUTF8());
    }

    std::printf ("\n%d wavetable files, %d problems\n", files.size(), problems);
    return problems > 0 ? 1 : 0;
}

int exportWavetables (const juce::File& dir, const juce::File& outDir)
{
    outDir.createDirectory();
    int written = 0;
    for (auto& f : dir.findChildFiles (juce::File::findFiles, false, "*.json"))
    {
        juce::var v;
        if (juce::JSON::parse (f.loadFileAsString(), v).failed()) continue;
        auto built = WavetableBank::buildFromJson (v, resolverFor (dir));
        if (! built.ok) continue;

        juce::AudioBuffer<float> audio (1, WavetableBank::numFrames * WavetableBank::tableSize);
        for (int frame = 0; frame < WavetableBank::numFrames; ++frame)
            audio.copyFrom (0, frame * WavetableBank::tableSize, built.data.data() + (size_t) frame * WavetableBank::tableSize, WavetableBank::tableSize);

        const auto out = outDir.getChildFile (juce::File::createLegalFileName (built.info.name) + ".wav");
        out.deleteFile();
        juce::WavAudioFormat wav;
        std::unique_ptr<juce::AudioFormatWriter> w (wav.createWriterFor (new juce::FileOutputStream (out), 44100.0, 1, 32, {}, 0));
        if (w != nullptr && w->writeFromAudioSampleBuffer (audio, 0, audio.getNumSamples()))
            ++written;
    }
    std::printf ("wrote %d wavetables to %s\n", written, outDir.getFullPathName().toRawUTF8());
    return written > 0 ? 0 : 1;
}

void wavetableSelftest (EmberlineProcessor& proc)
{
    std::printf ("expression language\n");
    auto eval = [] (const char* text, std::initializer_list<const char*> vars, std::initializer_list<double> values, juce::String* err = nullptr)
    {
        juce::String e;
        auto x = Expression::compile (text, juce::StringArray (vars.begin(), (int) vars.size()), e);
        if (err != nullptr) *err = e;
        if (! x) return std::nan ("");
        std::vector<double> v (values);
        return x->evaluate (v.data());
    };
    expect (std::abs (eval ("2+3*4", {}, {}) - 14.0) < 1e-9, "precedence: 2+3*4 = 14");
    expect (std::abs (eval ("-2^2", {}, {}) + 4.0) < 1e-9, "unary minus binds looser than ^: -2^2 = -4");
    expect (std::abs (eval ("pow(2,10)+if(1>0,5,6)", {}, {}) - 1029.0) < 1e-9, "functions and if()");
    expect (std::abs (eval ("1/h", { "h" }, { 4.0 }) - 0.25) < 1e-9, "variables");
    expect (std::abs (eval ("fm(1,1,0)", {}, {}) - 1.0) < 1e-9 && std::abs (eval ("fm(3,1,0)", {}, {})) < 1e-9, "fm(): index 0 is a pure sine");
    expect (std::abs (eval ("odd(3)+even(4)+fib(13)+prime(7)", {}, {}) - 4.0) < 1e-9, "odd / even / fib / prime helpers");
    {
        juce::String err;
        eval ("sin(", {}, {}, &err);       expect (err.isNotEmpty(), "syntax error reported: " + err);
        eval ("nope(1)", {}, {}, &err);    expect (err.contains ("unknown function"), "unknown function reported: " + err);
        eval ("x+1", {}, {}, &err);        expect (err.contains ("unknown name"), "unknown variable reported: " + err);
        eval ("pow(1)", {}, {}, &err);     expect (err.contains ("argument"), "wrong argument count reported: " + err);
        eval ("1/0", {}, {}, &err);        expect (std::abs (eval ("1/0", {}, {})) < 1e-9, "division by zero is safe (0)");
    }

    std::printf ("wavetable bank\n");
    auto& bank = WavetableBank::shared();
    expect (bank.numFactoryTables() >= 28, juce::String (bank.numFactoryTables()) + " factory wavetables embedded");

    juce::StringArray seen;
    bool unique = true, normalised = true, allSound = true;
    for (int t = 0; t < bank.numFactoryTables(); ++t)
    {
        if (seen.contains (bank.info (t).name, true)) unique = false;
        seen.add (bank.info (t).name);
        for (int f = 0; f < WavetableBank::numFrames; ++f)
        {
            float peak = 0.0f;
            for (int n = 0; n < WavetableBank::tableSize; ++n) peak = std::max (peak, std::abs (bank.table (t, 0, f)[n]));
            if (peak < 0.5f) allSound = false;
            if (peak > 1.001f) normalised = false;
        }
    }
    expect (unique, "factory table names are unique");
    expect (allSound && normalised, "every frame of every table has sound and is peak-normalised (<= 1.0)");

    const int classic = bank.indexOfName ("Classic Morph");
    float worst = 0.0f;
    for (int n = 0; n < WavetableBank::tableSize; ++n)
        worst = std::max (worst, std::abs (bank.table (classic, 0, 0)[n] - std::sin (juce::MathConstants<float>::twoPi * (float) n / WavetableBank::tableSize)));
    expect (worst < 2.0e-3f, "FFT calibration: Classic Morph frame 1 is a sine to within " + juce::String (worst, 5));

    const int pulse = bank.indexOfName ("Pulse Width");
    const auto* sq = bank.table (pulse, 0, 0);
    {
        // a band-limited square rings at its edges (Gibbs), so check what matters: flat plateaus with the right sign
        const float top = sq[WavetableBank::tableSize / 4], topLater = sq[WavetableBank::tableSize / 4 + 200];
        const float bottom = sq[3 * WavetableBank::tableSize / 4];
        expect (top > 0.8f && bottom < -0.8f && std::abs (top - topLater) < 0.01f && std::abs (top + bottom) < 0.01f,
                "Pulse Width frame 1 is a flat, symmetric square (plateau " + juce::String (top, 3) + " / " + juce::String (bottom, 3) + ")");
    }

    {   // band-limiting: the darkest mip keeps one harmonic only, so it must be a pure sinusoid
        const int pl = bank.indexOfName ("Pluck Position");
        const auto* t = bank.table (pl, WavetableBank::numMips - 1, WavetableBank::numFrames - 1);
        double a = 0, b = 0;
        for (int n = 0; n < WavetableBank::tableSize; ++n)
        {
            const double ph = juce::MathConstants<double>::twoPi * n / WavetableBank::tableSize;
            a += t[n] * std::sin (ph) * 2.0 / WavetableBank::tableSize;
            b += t[n] * std::cos (ph) * 2.0 / WavetableBank::tableSize;
        }
        double residual = 0.0;
        for (int n = 0; n < WavetableBank::tableSize; ++n)
        {
            const double ph = juce::MathConstants<double>::twoPi * n / WavetableBank::tableSize;
            residual = std::max (residual, std::abs (t[n] - (a * std::sin (ph) + b * std::cos (ph))));
        }
        expect (residual < 1.0e-3, "band-limiting: the 1-harmonic mip is a pure sinusoid (residual " + juce::String (residual, 6) + ")");
    }

    std::printf ("sampled (WAV) tables and phase alignment\n");
    {
        // two frames of the same waveform, the second shifted by 0.3 of a cycle: aligned import must make them identical
        auto makeWav = [] (int cycles, float shiftOfSecond)
        {
            juce::AudioBuffer<float> audio (1, 2048 * cycles);
            for (int f = 0; f < cycles; ++f)
                for (int n = 0; n < 2048; ++n)
                {
                    const float ph = (float) n / 2048.0f + (f == 1 ? shiftOfSecond : 0.0f);
                    audio.setSample (0, f * 2048 + n, std::sin (juce::MathConstants<float>::twoPi * ph) + 0.5f * std::sin (juce::MathConstants<float>::twoPi * 2.0f * ph + 0.7f)
                                                       + 0.3f * std::sin (juce::MathConstants<float>::twoPi * 3.0f * ph + 1.9f));
                }
            // (the writer owns and deletes its stream, so go through a temporary file)
            const auto tmp = juce::File::createTempFile (".wav");
            {
                juce::WavAudioFormat wav;
                std::unique_ptr<juce::AudioFormatWriter> w (wav.createWriterFor (new juce::FileOutputStream (tmp), 44100.0, 1, 24, {}, 0));
                w->writeFromAudioSampleBuffer (audio, 0, audio.getNumSamples());
            }
            juce::MemoryBlock bytes;
            tmp.loadFileAsData (bytes);
            tmp.deleteFile();
            return bytes;
        };

        auto correlation = [] (const WavetableBank::Built& b)
        {
            const float* a = b.data.data();
            const float* c = b.data.data() + (size_t) (WavetableBank::numFrames - 1) * WavetableBank::tableSize;
            double ab = 0, aa = 0, cc = 0;
            for (int n = 0; n < WavetableBank::tableSize; ++n) { ab += (double) a[n] * c[n]; aa += (double) a[n] * a[n]; cc += (double) c[n] * c[n]; }
            return ab / std::sqrt (aa * cc + 1.0e-12);
        };

        const auto block = makeWav (2, 0.3f);
        auto aligned = WavetableBank::buildFromAudio (std::make_unique<juce::MemoryInputStream> (block, true), "t", "test", 2048, true);
        auto raw = WavetableBank::buildFromAudio (std::make_unique<juce::MemoryInputStream> (block, true), "t", "test", 2048, false);
        expect (aligned.ok && raw.ok, "an in-memory 2-frame WAV imports");
        expect (correlation (aligned) > 0.999, "phase alignment: a shifted copy becomes the identical frame (correlation " + juce::String (correlation (aligned), 4) + ")");
        expect (correlation (raw) < 0.9, "...whereas without alignment the frames stay offset (correlation " + juce::String (correlation (raw), 3) + ")");

        // every sampled factory table should have its fundamental in sine phase on every frame
        int checked = 0, misaligned = 0;
        for (int t = 0; t < bank.numFactoryTables(); ++t)
            if (bank.info (t).source.endsWithIgnoreCase (".wav"))
            {
                ++checked;
                for (int f = 0; f < WavetableBank::numFrames; ++f)
                {
                    const float* x = bank.table (t, 0, f);
                    double a = 0.0, c = 0.0;
                    for (int n = 0; n < WavetableBank::tableSize; ++n)
                    {
                        const double ph = juce::MathConstants<double>::twoPi * n / WavetableBank::tableSize;
                        a += x[n] * std::sin (ph);
                        c += x[n] * std::cos (ph);
                    }
                    if (std::hypot (a, c) > 20.0 && std::abs (c) > 0.12 * std::abs (a))   // fundamental present but not in sine phase
                        ++misaligned;
                }
            }
        const int totalFrames = checked * WavetableBank::numFrames;
        expect (checked >= 20 && misaligned * 100 <= totalFrames * 5,
                juce::String (checked) + " sampled tables loaded; " + juce::String (misaligned) + " of " + juce::String (totalFrames)
                    + " frames have the fundamental out of sine phase (those are frames dominated by a higher harmonic, aligned to that one instead)");
    }

    std::printf ("malformed wavetable definitions are rejected with a useful message\n");
    auto tryBuild = [] (const char* json)
    {
        juce::var v;
        juce::JSON::parse (json, v);
        return WavetableBank::buildFromJson (v);
    };
    { auto r = tryBuild (R"({"name":"x","mode":"spectrum","amplitude":"1/(h"})");        expect (! r.ok && r.error.contains ("amplitude"), "bad expression: " + r.error); }
    { auto r = tryBuild (R"({"mode":"spectrum","amplitude":"1/h"})");                    expect (! r.ok && r.error.contains ("name"), "missing name: " + r.error); }
    { auto r = tryBuild (R"({"name":"x","mode":"wobble"})");                              expect (! r.ok && r.error.contains ("mode"), "unknown mode: " + r.error); }
    { auto r = tryBuild (R"({"name":"x","mode":"spectrum","amplitude":"0"})");           expect (! r.ok && r.error.contains ("silent"), "silent table: " + r.error); }
    { auto r = tryBuild (R"({"name":"x","mode":"morph","stages":[{"harmonics":[1]}]})"); expect (! r.ok && r.error.contains ("two"), "one stage only: " + r.error); }
    { auto r = tryBuild (R"({"name":"ok","mode":"morph","stages":[{"harmonics":[1]},{"harmonics":{"2":[1,0.25]}}]})"); expect (r.ok, "minimal morph with explicit harmonics builds"); }

    std::printf ("user wavetables (JSON + WAV in the user folder)\n");
    {
        const auto dir = WavetableBank::userDirectory();
        dir.createDirectory();
        const auto jsonFile = dir.getChildFile ("zz-selftest-table.json");
        const auto wavFile = dir.getChildFile ("zz-selftest-wav.wav");
        const auto before = dir.findChildFiles (juce::File::findFiles, false, "*.json;*.wav").size();

        jsonFile.replaceWithText (R"({"name":"ZZ Selftest Table","category":"User","description":"temporary","mode":"waveform","expression":"sin(tau*phase)*(1-t)+saw(phase)*t"})", false, false, "\n");
        {
            juce::AudioBuffer<float> cycle (1, 600);
            for (int i = 0; i < 600; ++i) cycle.setSample (0, i, std::sin (juce::MathConstants<float>::twoPi * (float) i / 600.0f) + 0.3f * std::sin (6.0f * juce::MathConstants<float>::twoPi * (float) i / 600.0f));
            juce::WavAudioFormat wav;
            std::unique_ptr<juce::AudioFormatWriter> w (wav.createWriterFor (new juce::FileOutputStream (wavFile), 44100.0, 1, 16, {}, 0));
            w->writeFromAudioSampleBuffer (cycle, 0, 600);
        }

        const auto problems = bank.scanUserTables();
        const int userJson = bank.indexOfName ("ZZ Selftest Table"), userWav = bank.indexOfName ("zz-selftest-wav");
        expect (problems.isEmpty() && userJson >= bank.numFactoryTables() && userWav >= bank.numFactoryTables(), "JSON and WAV tables load into user slots (" + problems.joinIntoString (", ") + ")");
        if (userJson >= 0 && userWav >= 0)
        {
            float peakJ = 0.0f, peakW = 0.0f;
            for (int n = 0; n < WavetableBank::tableSize; ++n)
            {
                peakJ = std::max (peakJ, std::abs (bank.table (userJson, 0, 8)[n]));
                peakW = std::max (peakW, std::abs (bank.table (userWav, 0, 3)[n]));
            }
            expect (peakJ > 0.99f && peakW > 0.99f, "user tables are generated and normalised");

            // a preset can name a user table directly, and capture writes that name back
            juce::var preset;
            juce::JSON::parse (R"({"name":"t","category":"User","parameters":{"osc2_table":"ZZ Selftest Table","osc3_table":"Pulse Width"}})", preset);
            const auto r = presets::apply (proc, preset);
            expect (r.warnings.isEmpty() && juce::roundToInt (proc.apvts.getRawParameterValue ("osc2_table")->load()) == userJson
                        && juce::roundToInt (proc.apvts.getRawParameterValue ("osc3_table")->load()) == bank.indexOfName ("Pulse Width"),
                    "presets select wavetables by name (factory and user)");
            const auto text = presets::toJson (presets::capture (proc, "t", "User"));
            expect (text.contains ("ZZ Selftest Table") && text.contains ("Pulse Width"), "saved presets store wavetable names, not slot numbers");
        }

        jsonFile.deleteFile();
        wavFile.deleteFile();
        bank.scanUserTables();
        expect (bank.indexOfName ("ZZ Selftest Table") < 0 && dir.findChildFiles (juce::File::findFiles, false, "*.json;*.wav").size() == before, "user files cleaned up");
    }
}

int snapshot (EmberlineProcessor& proc, const juce::File& dir, const juce::String& presetName)
{
    dir.createDirectory();
    if (presetName.isNotEmpty() && ! proc.loadPresetByName (presetName))
    {
        std::printf ("no preset called \"%s\"\n", presetName.toRawUTF8());
        return 1;
    }

    // let the engine run so live displays (LFO playheads, chaos trail, mesh traces) have content
    proc.prepareToPlay (sampleRate, blockSize);
    juce::AudioBuffer<float> block (2, blockSize);
    juce::MidiBuffer first;
    for (int n : { 48, 55, 58, 63 }) first.addEvent (juce::MidiMessage::noteOn (1, n, (juce::uint8) 100), 0);
    for (int b = 0; b < 300; ++b)
    {
        juce::MidiBuffer midi;
        if (b == 0) midi = first;
        proc.processBlock (block, midi);
    }

    std::unique_ptr<juce::AudioProcessorEditor> editor (proc.createEditor());
    const char* names[] { "1-visualizers", "2-lfos-chaos", "3-mod-matrix", "4-fx-chain", "5-filters-envs", "6-arp-stutter" };

    for (int page = 0; page < 6; ++page)
    {
        int index = 0;
        for (auto* child : editor->getChildren())
            if (auto* button = dynamic_cast<juce::TextButton*> (child))
                if (button->onClick != nullptr && index++ == page)   // the editor's direct TextButton children are the six tabs
                {
                    button->setToggleState (true, juce::dontSendNotification);   // a real click would light the tab as well
                    button->onClick();
                }

        const auto image = editor->createComponentSnapshot (editor->getLocalBounds(), true, 1.0f);
        const auto file = dir.getChildFile (juce::String (names[page]) + ".png");
        file.deleteFile();
        juce::FileOutputStream out (file);
        juce::PNGImageFormat().writeImageToStream (image, out);
        std::printf ("wrote %s\n", file.getFullPathName().toRawUTF8());
    }
    return 0;
}

// Opens every output device of every device type the way the standalone app does, then once more with the
// real processor attached and running, and prints exactly what happened. For "error opening audio device".
int audioDiag (EmberlineProcessor& proc)
{
    juce::AudioDeviceManager manager;
    int failures = 0, attempts = 0;

    for (auto* type : manager.getAvailableDeviceTypes())
    {
        type->scanForDevices();
        std::printf ("\n== device type: %s\n", type->getTypeName().toRawUTF8());
        const auto outputs = type->getDeviceNames (false);
        if (outputs.isEmpty()) { std::printf ("   (no output devices)\n"); continue; }

        manager.setCurrentAudioDeviceType (type->getTypeName(), true);

        for (auto& name : outputs)
        {
            juce::AudioDeviceManager::AudioDeviceSetup setup;
            manager.getAudioDeviceSetup (setup);
            setup.outputDeviceName = name;
            setup.inputDeviceName = {};
            setup.useDefaultInputChannels = false;
            setup.inputChannels.clear();
            setup.useDefaultOutputChannels = true;
            setup.sampleRate = 0.0;
            setup.bufferSize = 0;

            ++attempts;
            const auto error = manager.setAudioDeviceSetup (setup, true);
            if (error.isEmpty())
            {
                auto* dev = manager.getCurrentAudioDevice();
                std::printf ("   [ OK ] %-52s %.0f Hz, %d samples, %d out ch\n", name.toRawUTF8(), dev->getCurrentSampleRate(),
                             dev->getCurrentBufferSizeSamples(), dev->getActiveOutputChannels().countNumberOfSetBits());
            }
            else
            {
                ++failures;
                std::printf ("   [FAIL] %-52s %s\n", name.toRawUTF8(), error.toRawUTF8());
            }
            manager.closeAudioDevice();
        }
    }

    std::printf ("\n== with the plugin attached (default device, as the standalone does it)\n");
    {
        juce::AudioProcessorPlayer player;
        player.setProcessor (&proc);
        juce::String error = manager.initialiseWithDefaultDevices (0, 2);
        manager.addAudioCallback (&player);
        std::printf ("   initialise: %s\n", error.isEmpty() ? "OK" : error.toRawUTF8());

        if (auto* dev = manager.getCurrentAudioDevice())
        {
            std::printf ("   device: %s (%s), %.0f Hz, %d samples\n", dev->getName().toRawUTF8(), dev->getTypeName().toRawUTF8(),
                         dev->getCurrentSampleRate(), dev->getCurrentBufferSizeSamples());
            juce::MidiBuffer midi;
            midi.addEvent (juce::MidiMessage::noteOn (1, 60, (juce::uint8) 100), 0);
            player.handleIncomingMidiMessage (nullptr, juce::MidiMessage::noteOn (1, 60, (juce::uint8) 100));
            juce::Thread::sleep (1500);
            std::printf ("   ran for 1.5 s with a note held: %s, cpu load %.1f%%\n", dev->isPlaying() ? "audio callback active" : "NOT playing", manager.getCpuUsage() * 100.0);
        }
        else
            ++failures;

        manager.removeAudioCallback (&player);
        manager.closeAudioDevice();
        player.setProcessor (nullptr);
    }

    std::printf ("\n%d of %d device opens failed\n", failures, attempts);
    return failures == 0 ? 0 : 1;
}

// Every output device x sample rate x buffer size, with the plugin attached and running, failures only.
int audioSweep (EmberlineProcessor& proc)
{
    juce::AudioDeviceManager manager;
    juce::AudioProcessorPlayer player;
    player.setProcessor (&proc);
    int attempts = 0, failures = 0;

    for (auto* type : manager.getAvailableDeviceTypes())
    {
        type->scanForDevices();
        manager.setCurrentAudioDeviceType (type->getTypeName(), true);

        for (auto& name : type->getDeviceNames (false))
            for (double rate : { 44100.0, 48000.0, 96000.0 })
                for (int buffer : { 64, 128, 256, 512, 1024 })
                {
                    juce::AudioDeviceManager::AudioDeviceSetup setup;
                    manager.getAudioDeviceSetup (setup);
                    setup.outputDeviceName = name;
                    setup.inputDeviceName = {};
                    setup.useDefaultInputChannels = false;
                    setup.inputChannels.clear();
                    setup.useDefaultOutputChannels = true;
                    setup.sampleRate = rate;
                    setup.bufferSize = buffer;

                    ++attempts;
                    manager.removeAudioCallback (&player);
                    const auto error = manager.setAudioDeviceSetup (setup, true);
                    if (error.isNotEmpty())
                    {
                        ++failures;
                        std::printf ("[FAIL] %s | %s | %.0f Hz | %d samples -> %s\n", type->getTypeName().toRawUTF8(), name.toRawUTF8(), rate, buffer, error.toRawUTF8());
                        continue;
                    }

                    manager.addAudioCallback (&player);
                    player.handleIncomingMidiMessage (nullptr, juce::MidiMessage::noteOn (1, 60, (juce::uint8) 100));
                    juce::Thread::sleep (120);
                    player.handleIncomingMidiMessage (nullptr, juce::MidiMessage::noteOff (1, 60));

                    auto* dev = manager.getCurrentAudioDevice();
                    if (dev == nullptr || ! dev->isPlaying())
                    {
                        ++failures;
                        std::printf ("[FAIL] %s | %s | %.0f Hz | %d samples -> opened but not playing\n", type->getTypeName().toRawUTF8(), name.toRawUTF8(), rate, buffer);
                    }
                }
    }

    manager.removeAudioCallback (&player);
    manager.closeAudioDevice();
    player.setProcessor (nullptr);
    std::printf ("\nsweep: %d of %d combinations failed\n", failures, attempts);
    return failures == 0 ? 0 : 1;
}

// Mimics the standalone's Options dialog: start from the default setup (which may include a default
// *input* device) and only change the output device, leaving the input exactly as JUCE leaves it.
int audioUiLike (EmberlineProcessor& proc)
{
    juce::AudioDeviceManager manager;
    juce::AudioProcessorPlayer player;
    player.setProcessor (&proc);

    const auto initError = manager.initialise (0, 2, nullptr, true);   // what the standalone asks for
    juce::AudioDeviceManager::AudioDeviceSetup start;
    manager.getAudioDeviceSetup (start);
    std::printf ("initialise(0 in, 2 out): %s\n", initError.isEmpty() ? "OK" : initError.toRawUTF8());
    std::printf ("  type=%s\n  output='%s'\n  input='%s'  useDefaultIn=%d  inputChannels=%d  outputChannels=%d\n",
                 manager.getCurrentAudioDeviceType().toRawUTF8(), start.outputDeviceName.toRawUTF8(), start.inputDeviceName.toRawUTF8(),
                 (int) start.useDefaultInputChannels, start.inputChannels.countNumberOfSetBits(), start.outputChannels.countNumberOfSetBits());

    int attempts = 0, failures = 0;
    for (auto* type : manager.getAvailableDeviceTypes())
    {
        type->scanForDevices();
        manager.setCurrentAudioDeviceType (type->getTypeName(), true);

        for (auto& name : type->getDeviceNames (false))
        {
            juce::AudioDeviceManager::AudioDeviceSetup setup;
            manager.getAudioDeviceSetup (setup);   // keeps whatever input JUCE selected
            setup.outputDeviceName = name;

            ++attempts;
            manager.removeAudioCallback (&player);
            const auto error = manager.setAudioDeviceSetup (setup, true);
            if (error.isNotEmpty())
            {
                ++failures;
                std::printf ("[FAIL] %s | out='%s' in='%s' -> %s\n", type->getTypeName().toRawUTF8(), name.toRawUTF8(), setup.inputDeviceName.toRawUTF8(), error.toRawUTF8());
            }
            else
                manager.addAudioCallback (&player);
        }
    }

    manager.removeAudioCallback (&player);
    manager.closeAudioDevice();
    player.setProcessor (nullptr);
    std::printf ("\nui-like: %d of %d failed\n", failures, attempts);
    return failures == 0 ? 0 : 1;
}

int main (int argc, char** argv)
{
    juce::ScopedJuceInitialiser_GUI init;
    juce::StringArray args;
    for (int i = 1; i < argc; ++i) args.add (argv[i]);

    EmberlineProcessor proc;

    if (args.size() >= 2 && args[0] == "snapshot")
        return snapshot (proc, juce::File::getCurrentWorkingDirectory().getChildFile (args[1]), args.size() >= 3 ? args[2] : juce::String());

    if (args.size() >= 2 && args[0] == "audio-diag" && args[1] == "--ui-like")
        return audioUiLike (proc);

    if (args.size() >= 2 && args[0] == "audio-diag" && args[1] == "--sweep")
        return audioSweep (proc);

    if (args.size() >= 1 && args[0] == "check-wavetables")
        return checkWavetables (juce::File::getCurrentWorkingDirectory().getChildFile (args.size() >= 2 ? args[1] : "Wavetables/Factory"));

    if (args.size() >= 2 && args[0] == "export-wavetables")
        return args.size() >= 3 ? exportWavetables (juce::File::getCurrentWorkingDirectory().getChildFile (args[1]), juce::File::getCurrentWorkingDirectory().getChildFile (args[2]))
                                : exportWavetables (juce::File::getCurrentWorkingDirectory().getChildFile ("Wavetables/Factory"), juce::File::getCurrentWorkingDirectory().getChildFile (args[1]));

    if (args.size() >= 1 && args[0] == "audio-diag")
        return audioDiag (proc);

    if (args.size() >= 1 && args[0] == "perf")
        return perf (proc);

    if (args.size() >= 1 && args[0] == "selftest")
        return selftest (proc);

    if (args.size() >= 2 && args[0] == "dump-params")
        return dumpParams (proc, juce::File::getCurrentWorkingDirectory().getChildFile (args[1]));

    if (args.size() >= 2 && args[0] == "check")
    {
        juce::File wavDir;
        double target = -20.0;
        bool fix = false;
        for (int i = 2; i < args.size(); ++i)
        {
            if (args[i] == "--wav" && i + 1 < args.size())    wavDir = juce::File::getCurrentWorkingDirectory().getChildFile (args[++i]);
            else if (args[i] == "--fix-levels")               fix = true;
            else if (args[i] == "--target" && i + 1 < args.size()) target = args[++i].getDoubleValue();
        }
        return check (proc, juce::File::getCurrentWorkingDirectory().getChildFile (args[1]), wavDir, fix, target);
    }

    if (args.size() >= 3 && args[0] == "render")
    {
        const auto file = juce::File::getCurrentWorkingDirectory().getChildFile (args[1]);
        juce::var v;
        juce::String error;
        if (! presets::parse (file.loadFileAsString(), v, error)) { std::printf ("parse error: %s\n", error.toRawUTF8()); return 1; }
        for (auto& w : presets::apply (proc, v).warnings) std::printf ("WARN %s\n", w.toRawUTF8());
        auto m = render (proc, v["category"].toString());
        std::printf ("peak %.1f dB, rms %.1f dB\n", m.peakDb, m.rmsDb);
        return writeWav (m.audio, juce::File::getCurrentWorkingDirectory().getChildFile (args[2])) ? 0 : 1;
    }

    std::printf ("usage:\n"
                 "  EmberlineTools dump-params <outdir>\n"
                 "  EmberlineTools check <presetdir> [--wav <outdir>] [--fix-levels] [--target <rms dBFS>]\n"
                 "  EmberlineTools render <preset.json> <out.wav>\n"
                 "  EmberlineTools check-wavetables [dir]\n"
                 "  EmberlineTools export-wavetables [dir] <outdir>\n"
                 "  EmberlineTools selftest\n"
                 "  EmberlineTools perf            (CPU use of heavy patches and every factory preset; use a Release build)\n"
                 "  EmberlineTools snapshot <outdir> [preset name]\n"
                 "  EmberlineTools audio-diag [--sweep | --ui-like]   (debug 'error opening audio device')\n");
    return 2;
}
